  /**
   * Helper to copy candidate interview talking points to clipboard.
   */
  public static async copyTalkingPoints(dossier: CompanyResearchDossier): Promise<boolean> {
    const text = `INTERVIEW TALKING POINTS FOR ${dossier.companyName.toUpperCase()}:
${dossier.candidateAngle.interviewTalkingPoints.map((tp, i) => `${i + 1}. ${tp}`).join('\n\n')}

HIGH-CONVICTION QUESTIONS TO ASK:
${dossier.candidateAngle.questionsToAskInterviewer.map((q, i) => `${i + 1}. "${q}"`).join('\n')}`;

    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      return false;
    }
  }

