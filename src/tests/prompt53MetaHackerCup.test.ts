import { describe, it, expect } from 'vitest';
import React from 'react';
import { renderToString } from 'react-dom/server';
import { HACKATHONS_DATABASE, HackathonsService } from '../services/hackathonsService';
import { HackathonsPortal } from '../components/HackathonsPortal';
import { HackathonWhitePageModal } from '../components/HackathonWhitePageModal';
import { isHostnameAllowed, validateSafeTargetUrl } from '../services/linkAllowlistService';

describe('Prompt 53: Meta Hacker Cup Coding Contest Integration & Constraints', () => {
  const hackerCup = HACKATHONS_DATABASE.find(h => h.name === 'Meta Hacker Cup');

  it('contains Meta Hacker Cup in HACKATHONS_DATABASE with type "coding-contest"', () => {
    expect(hackerCup).toBeDefined();
    expect(hackerCup!.type).toBe('coding-contest');
    expect(hackerCup!.organizer).toBe('Meta');
  });

  it('sets status strictly to NOT_ANNOUNCED', () => {
    expect(hackerCup!.status).toBe('NOT_ANNOUNCED');
  });

  it('contains the exact specified lastEditionNote verbatim', () => {
    const expectedNote =
      '2025 season: registration opened 3 October 2025, free, main track age 18+, high-school division needs parental consent, prizes include T-shirts and cash for finalists, some countries excluded from prize shipping. 2026 season not announced as of the last check; confirm on the official Hacker Cup page.';
    expect(hackerCup!.lastEditionNote).toBe(expectedNote);
  });

  it('sets prizeText to "not listed"', () => {
    expect(hackerCup!.prizeText.toLowerCase()).toBe('not listed');
  });

  it('strictly does NOT mention interviews anywhere in the entry', () => {
    const allText = [
      hackerCup!.name,
      hackerCup!.organizer,
      hackerCup!.description,
      hackerCup!.eligibilityText,
      hackerCup!.prizeText,
      hackerCup!.datesNote,
      hackerCup!.lastEditionNote
    ].filter(Boolean).join(' ').toLowerCase();

    expect(allText).not.toContain('interview');
    expect(allText).not.toContain('interviews');
  });

  it('points to the official Hacker Cup page and is permitted on the link allowlist', async () => {
    expect(hackerCup!.officialUrl).toContain('facebook.com/codingcompetitions/hacker-cup');
    expect(isHostnameAllowed('facebook.com')).toBe(true);
    expect(isHostnameAllowed('www.facebook.com')).toBe(true);

    const safeUrlCheck = await validateSafeTargetUrl(hackerCup!.officialUrl);
    expect(safeUrlCheck.safe).toBe(true);
  });

  it('correctly filters Meta Hacker Cup under coding-contest filter', () => {
    const contests = HackathonsService.filterHackathons(HACKATHONS_DATABASE, { type: 'coding-contest' });
    expect(contests.some(c => c.name === 'Meta Hacker Cup')).toBe(true);
    expect(contests.some(c => c.name === 'TCS CodeVita')).toBe(true);

    const hackathons = HackathonsService.filterHackathons(HACKATHONS_DATABASE, { type: 'hackathon' });
    expect(hackathons.every(h => h.name !== 'Meta Hacker Cup')).toBe(true);
  });

  it('correctly filters Meta Hacker Cup under NOT_ANNOUNCED status filter', () => {
    const notAnnounced = HackathonsService.filterHackathons(HACKATHONS_DATABASE, { status: 'NOT_ANNOUNCED' });
    expect(notAnnounced.some(h => h.name === 'Meta Hacker Cup')).toBe(true);
  });

  it('renders HackathonWhitePageModal for Meta Hacker Cup since status is NOT_ANNOUNCED', () => {
    const html = renderToString(
      React.createElement(HackathonWhitePageModal, {
        hackathon: hackerCup!,
        isOpen: true,
        onClose: () => {},
      })
    );
    expect(html).toContain('Meta Hacker Cup');
    expect(html).toContain('Summary generated by TERRASYNX');
  });

  it('renders Meta Hacker Cup card on HackathonsPortal with coding-contest badge and lastEditionNote', () => {
    const html = renderToString(React.createElement(HackathonsPortal));
    expect(html).toContain('Meta Hacker Cup');
    expect(html).toContain('coding-contest');
    expect(html).toContain('prizes include T-shirts and cash for finalists');
    expect(html).toContain('2026 season not announced as of the last check');
  });
});
